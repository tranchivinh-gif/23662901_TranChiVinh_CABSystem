#!/bin/sh
set -eu
. /run/cab-secrets/config.env
case "${CAB_DB_PREFIX:-}" in
  IDENTITY_ACCOUNT) POSTGRES_PASSWORD="$IDENTITY_ACCOUNT_DB_ADMIN_PASSWORD"; CAB_RUNTIME_PASSWORD="$IDENTITY_ACCOUNT_DB_PASSWORD"; CAB_MIGRATION_PASSWORD="$IDENTITY_ACCOUNT_DB_MIGRATION_PASSWORD" ;;
  CUSTOMER) POSTGRES_PASSWORD="$CUSTOMER_DB_ADMIN_PASSWORD"; CAB_RUNTIME_PASSWORD="$CUSTOMER_DB_PASSWORD"; CAB_MIGRATION_PASSWORD="$CUSTOMER_DB_MIGRATION_PASSWORD" ;;
  DRIVER) POSTGRES_PASSWORD="$DRIVER_DB_ADMIN_PASSWORD"; CAB_RUNTIME_PASSWORD="$DRIVER_DB_PASSWORD"; CAB_MIGRATION_PASSWORD="$DRIVER_DB_MIGRATION_PASSWORD" ;;
  BOOKING) POSTGRES_PASSWORD="$BOOKING_DB_ADMIN_PASSWORD"; CAB_RUNTIME_PASSWORD="$BOOKING_DB_PASSWORD"; CAB_MIGRATION_PASSWORD="$BOOKING_DB_MIGRATION_PASSWORD" ;;
  TRIP) POSTGRES_PASSWORD="$TRIP_DB_ADMIN_PASSWORD"; CAB_RUNTIME_PASSWORD="$TRIP_DB_PASSWORD"; CAB_MIGRATION_PASSWORD="$TRIP_DB_MIGRATION_PASSWORD" ;;
  PAYMENT) POSTGRES_PASSWORD="$PAYMENT_DB_ADMIN_PASSWORD"; CAB_RUNTIME_PASSWORD="$PAYMENT_DB_PASSWORD"; CAB_MIGRATION_PASSWORD="$PAYMENT_DB_MIGRATION_PASSWORD" ;;
  NOTIFICATION) POSTGRES_PASSWORD="$NOTIFICATION_DB_ADMIN_PASSWORD"; CAB_RUNTIME_PASSWORD="$NOTIFICATION_DB_PASSWORD"; CAB_MIGRATION_PASSWORD="$NOTIFICATION_DB_MIGRATION_PASSWORD" ;;
  *) echo 'Invalid DB owner' >&2; exit 1 ;;
esac
export POSTGRES_PASSWORD CAB_RUNTIME_PASSWORD CAB_MIGRATION_PASSWORD
